(** * Definitions and properties of $\alpha$-equivalence 

The first definition, which can be found in %\cite{urbanNominalUnification2004,limaFormalizedExtensionSubstitution2023,ayala-rinconNominalSyntaxPermutation2020,dominguezNominalSyntaxAtom2021}%, is given by the following rules:

%\begin{definition}\label{def:aeq}
\begin{mathpar}
\inferrule*[Right={({\rm\it aeq\_app})}]{t_1 =_a t_1' \and t_2 =_a t_2'}{t_1\ t_2 =_a t_1'\ t_2'} \and \inferrule*[Right={({\rm\it aeq\_abs\_same})}]{t_1 =_a t_2}{\lambda_x.t_1 =_a \lambda_x.t_2} \\
 \inferrule*[Left={({\rm\it aeq\_var})}]{~}{x =_a x} \and
\inferrule*[Right={({\rm\it aeq\_abs\_diff})}]{x \neq y \and x \notin fv(t_2) \and t_1 =_a \swap{y}{x}{t_2}}{\lambda_x.t_1 =_a \lambda_y.t_2} 
\end{mathpar}
\end{definition}

\noindent% where $\swap{y}{x}{t_2}$ denotes the term obtained from $t_2$ by swapping the names $x$ and $y$. The building block of the nominal approach is the _swap_ operation, a transposition of two names, from which arbitrary finite permutations can be built. The swap operation is first defined on atoms (left) and then extended to terms (right):

%\[
  \vswap{x}{y}{z} := \left\{\begin{array}{ll}
    y & \mbox{if } z = x \\
    x & \mbox{if } z = y \\
    z & \mbox{otherwise}
  \end{array}\right.
  \qquad
  \swap{x}{y}{t} := \left\{\begin{array}{ll}
    \vswap{x}{y}{z} & \mbox{if } t \mbox{ is a variable } z \\
    \lambda_{\vswap{x}{y}{z}}.\swap{x}{y}{t_1} & \mbox{if } t = \lambda_z.t_1 \\
    \swap{x}{y}{t_1}\ \swap{x}{y}{t_2} & \mbox{if } t = t_1\ t_2
  \end{array}\right.
\]% *)
(* begin hide *)
Definition Rel (A: Type) := A -> A -> Prop.

Reserved Notation "t1 =a t2"
    (at level 60, format "t1  '=a'  t2").

Inductive aeq : Rel nexp :=
| aeq_var : forall x, n_var x =a n_var x
| aeq_abs_same : forall x t1 t2, t1 =a t2 ->
                                 n_abs x t1 =a n_abs x t2
| aeq_abs_diff : forall x y t1 t2, x <> y -> x \notin fv t2 ->
                                   t1 =a (swap y x t2) ->
                                   n_abs x t1 =a n_abs y t2
| aeq_app : forall t1 t2 t1' t2', t1 =a t1' -> t2 =a t2' ->
                                  n_app t1 t2 =a n_app t1' t2'
where "t =a u" := (aeq t u).
(* end hide *)
