Reserved Notation "t1 =p t2"
    (at level 60, format "t1  '=p'  t2").

Inductive aeqp : Rel nexp :=
| p_var: forall x, n_var x =p n_var x
| p_abs: forall x y z t1 t2, z <> x -> z <> y ->
                             z \notin (fv t1) \u (fv t2) -> 
                             swap x z t1 =p (swap y z t2) ->
                             n_abs x t1 =p n_abs y t2
| p_app: forall t1 t2 t1' t2', t1 =p t1' ->
                               t2 =p t2' ->
                               n_app t1 t2 =p n_app t1' t2'
where "t =p u" := (aeqp t u).
(* end hide *)
