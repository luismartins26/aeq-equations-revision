Fixpoint fv (t : nexp) : atoms :=
  match t with
  | n_var x => {{x}}
  | n_abs x t1 => remove x (fv t1)
  | n_app t1 t2 => fv t1 `union` fv t2
  end.

Fixpoint bv_nom (t : nexp) : atoms :=
  match t with
  | n_var x => {}
  | n_abs x t1 => {{x}} `union` (bv_nom t1)
  | n_app t1 t2 => bv_nom t1 `union` bv_nom t2
  end.

Fixpoint size (t : nexp) : nat :=
  match t with
  | n_var x => 1
  | n_abs x t => 1 + size t
  | n_app t1 t2 => 1 + size t1 + size t2
  end.
