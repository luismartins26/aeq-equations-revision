Theorem aeq_aeqp: forall t1 t2, t1 =a t2 -> t1 =p t2.
Proof. 
  induction 1.
  - apply p_var.
  - pick fresh y for ({{x}} \u fv t1 \u fv t2). apply p_abs with y.
    + apply notin_union_1 in Fr. apply notin_singleton_1 in Fr. symmetry; assumption.
    + apply notin_union_1 in Fr. apply notin_singleton_1 in Fr. symmetry; assumption.
    + apply notin_union_2 in Fr. assumption.
    + apply aeqp_stable_swap. assumption.
  - pick fresh z for ({{x}} \u {{y}} \u fv t1 \u fv t2). apply p_abs with z.
    + apply notin_union_1 in Fr. apply notin_singleton_1 in Fr. symmetry; assumption.
    + apply notin_union_2 in Fr. apply notin_union_1 in Fr. apply notin_singleton_1 in Fr. symmetry; assumption.
