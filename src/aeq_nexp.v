    + apply (aeqp_stable_swap _ _ x z) in IHaeq. rewrite (swap_symmetric _ y z). apply aeqp_trans with (swap x z (swap y x t2)).
      * assumption.
      * rewrite swap_symmetric. rewrite (swap_symmetric _ y x). apply aeqp_swap_swap.
        ** repeat apply notin_union_2 in Fr. assumption.
        ** assumption.
  - apply p_app; assumption.
Qed.
